// Offline reader for Gordon Now's text-layer invoices. Unknown layouts fall
// back to reviewed manual/AI entry; a partial extraction is never accepted.
export interface GfsDraft {
  vendor: string;
  reference: string;
  date: string | null;
  total: number;
  subtotal: number | null;
  gst: number | null;
  other_tax: number | null;
  charges: number | null;
  lines: {
    description: string; item_code: string; cases: number; packets: number;
    unit_price: number; line_total: number; price_basis: "case" | "packet";
  }[];
}

/** Copy printed amounts only. In particular, total − lines is NOT assumed GST. */
export function readGfsInvoice(source: string): GfsDraft | null {
  const text = source.replace(/\s+/g, " ").trim();
  if (!/Gordon Now/i.test(text)) return null;
  const reference = /Invoice\s*#\s*(\d+)/i.exec(text)?.[1];
  const totalText = /Total Amount:\s*\$?([\d,]+(?:\.\d{1,2})?)/i.exec(text)?.[1];
  const expected = Number(/Total Items:\s*(\d+)/i.exec(text)?.[1]);
  if (!reference || !totalText || !Number.isSafeInteger(expected) || expected < 1 || expected > 2000) return null;
  const start = text.indexOf("Sales Unit");
  if (start < 0) return null;
  const body = text.slice(start + "Sales Unit".length).replace(/Generated by Gordon Now Application.*$/i, "");
  const pattern = /(\d{6,9})\s+(.+?)\s+(\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)\s+(\d+(?:\.\d{1,4})?)\s+(\d+(?:\.\d{1,2})?)\s+(CS|EA|PK)\b/g;
  const lines: GfsDraft["lines"] = [];
  let cursor = 0;
  for (const match of body.matchAll(pattern)) {
    if (body.slice(cursor, match.index).trim()) return null;
    const [, item_code, description, , confirmed, unitPrice, lineTotal, unit] = match;
    lines.push({
      item_code, description: description.trim(),
      cases: unit === "CS" ? Number(confirmed) : 0,
      packets: unit === "CS" ? 0 : Number(confirmed),
      unit_price: Number(unitPrice), line_total: Number(lineTotal),
      price_basis: unit === "CS" ? "case" : "packet",
    });
    cursor = match.index! + match[0].length;
  }
  if (lines.length !== expected || body.slice(cursor).trim()) return null;
  const printed = (label: string) => {
    const value = new RegExp(`\\b${label}:\\s*\\$?([\\d,]+(?:\\.\\d{1,2})?)`, "i").exec(text)?.[1];
    return value ? Number(value.replace(/,/g, "")) : null;
  };
  const date = /Invoice Date:\s*(\d{4}-\d{2}-\d{2})\b/i.exec(text)?.[1] ?? null;
  return { vendor: "Gordon Now", reference, date, total: Number(totalText.replace(/,/g, "")),
    subtotal: printed("Subtotal"), gst: printed("GST"), other_tax: printed("Other Tax"), charges: printed("Charges"), lines };
}
