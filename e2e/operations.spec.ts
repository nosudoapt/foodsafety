import { test, expect, capture, east, monthAt, signInFoodSafe, signInBtb } from "./fixtures";

function dateAhead(days: number) {
  const date = new Date();
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

test("documents recover from read failures and retain failed uploads and deletions", async ({ page, fixture }, info) => {
  await fixture.configure({ failures: [{ table: "business_documents", method: "GET", times: 1 }] });
  await signInFoodSafe(page, "owner", "/admin/documents");
  await expect(page.getByRole("heading", { name: "Documents are unavailable" })).toBeVisible();
  await page.getByRole("button", { name: "Retry documents" }).click();
  await expect(page.getByRole("article", { name: "Kitchen opening procedure", exact: true })).toBeVisible();
  await page.getByRole("searchbox", { name: "Search documents" }).fill("supplier");
  await expect(page.getByRole("article")).toHaveCount(1);
  await page.getByRole("searchbox", { name: "Search documents" }).clear();

  const trigger = page.getByRole("button", { name: "Upload document", exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "Upload document", exact: true });
  await expect(dialog.getByLabel("Document name")).toBeFocused();
  const close = dialog.getByRole("button", { name: "Close upload document" });
  await close.focus();
  await page.keyboard.press("Shift+Tab");
  await expect(dialog.getByRole("button", { name: "Cancel", exact: true })).toBeFocused(); // Submit is disabled until a file is selected.
  await page.keyboard.press("Tab");
  await expect(close).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(trigger).toBeFocused();
  await trigger.click();
  await expect(dialog.getByLabel("Document name")).toBeFocused();
  await dialog.getByLabel("Document name").fill("Evening handover SOP");
  await dialog.getByLabel("Notes (optional)").fill("Use before the closing team signs out.");
  await dialog.getByLabel("File", { exact: true }).setInputFiles({ name: "evening-handover.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.4\nEvening handover") });
  await fixture.configure({ failures: [{ table: "business_documents", method: "POST", times: 1 }] });
  await dialog.getByRole("button", { name: "Upload document", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("wasn’t uploaded");
  await expect(dialog.getByLabel("Document name")).toHaveValue("Evening handover SOP");
  expect((await fixture.state()).tables.business_documents.some((row) => row.name === "Evening handover SOP")).toBeFalsy();
  await page.setViewportSize({ width: 375, height: 812 });
  await capture(page, info, "mobile-document-upload");
  await dialog.getByRole("button", { name: "Upload document", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  const added = page.getByRole("article", { name: "Evening handover SOP", exact: true });
  await expect(added).toBeVisible();
  let state = await fixture.state();
  const saved = state.tables.business_documents.find((row) => row.name === "Evening handover SOP");
  expect(saved).toMatchObject({ restaurant_name: "The Test Kitchen", user_id: "10000000-0000-4000-8000-000000000003", uploaded_by: "10000000-0000-4000-8000-000000000003", file_name: "evening-handover.pdf" });
  const downloadEvent = page.waitForEvent("download");
  await added.getByRole("button", { name: "Download file" }).click();
  expect((await downloadEvent).suggestedFilename()).toBe("evening-handover.pdf");
  await fixture.configure({ failures: [{ table: "business_documents", method: "DELETE", times: 1 }] });
  page.on("dialog", (confirmation) => confirmation.accept());
  await added.getByRole("button", { name: "Delete Evening handover SOP" }).click();
  await expect(page.locator(".document-workspace").getByRole("alert")).toContainText("wasn’t deleted");
  await expect(added).toBeVisible();
  await capture(page, info, "mobile-document-library");
  await added.getByRole("button", { name: "Delete Evening handover SOP" }).click();
  await expect(added).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("article", { name: "Kitchen opening procedure", exact: true })).toBeVisible();
  await expect(added).toHaveCount(0);
  state = await fixture.state();
  expect(state.requests.filter((request) => request.path.endsWith("/business_documents") && request.method === "GET").every((request) => request.query.restaurant_name === "eq.The Test Kitchen")).toBeTruthy();
});

test("opening and closing drafts stay independent and only confirmed checks enter history", async ({ page, fixture }, info) => {
  await signInFoodSafe(page, "staff", "/checks");
  const checks = page.locator(".checks-columns");
  await checks.getByRole("checkbox").first().check();
  await page.getByLabel("Notes (optional)").fill("Opening draft: replace the sign bulb.");
  await page.getByRole("button", { name: "Closing Check", exact: true }).click();
  await expect(checks.getByRole("checkbox").first()).not.toBeChecked();
  await checks.getByRole("checkbox").nth(1).check();
  await page.getByLabel("Notes (optional)").fill("Closing draft: leave the keys in the safe.");
  await page.getByRole("button", { name: "Opening Check", exact: true }).click();
  await expect(checks.getByRole("checkbox").first()).toBeChecked();
  await expect(page.getByLabel("Notes (optional)")).toHaveValue("Opening draft: replace the sign bulb.");
  await fixture.configure({ failures: [{ table: "daily_checks", method: "POST", times: 1 }] });
  await page.getByRole("button", { name: "Save Partial Check" }).click();
  await expect(page.locator(".checks-save").getByRole("alert")).toContainText("wasn’t saved");
  await expect(checks.getByRole("checkbox").first()).toBeChecked();
  await page.getByRole("button", { name: "Save Partial Check" }).click();
  await expect(page.locator(".checks-save").getByRole("status")).toContainText("saved with partial progress");
  await expect(checks.getByRole("checkbox").first()).not.toBeChecked();
  await page.getByRole("button", { name: "Closing Check", exact: true }).click();
  await expect(checks.getByRole("checkbox").nth(1)).toBeChecked();
  await expect(page.getByLabel("Notes (optional)")).toHaveValue("Closing draft: leave the keys in the safe.");
  await capture(page, info, "daily-checks-drafts");
  await page.reload();
  const history = page.getByRole("button", { name: /Opening.*Partial.*Opening draft: replace the sign bulb/ });
  await history.click();
  await expect(history).toHaveAttribute("aria-expanded", "true");
  const state = await fixture.state();
  const saved = state.tables.daily_checks.find((row) => row.notes === "Opening draft: replace the sign bulb.");
  expect(saved).toMatchObject({ user_id: "10000000-0000-4000-8000-000000000001", restaurant_name: "The Test Kitchen", check_type: "opening", completed: false, completed_at: null });
  expect(saved).not.toHaveProperty("location_id");
  expect(state.tables.daily_checks.some((row) => row.notes === "Closing draft: leave the keys in the safe.")).toBeFalsy();
});

