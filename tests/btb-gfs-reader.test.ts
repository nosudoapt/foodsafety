import test from "node:test";
import assert from "node:assert/strict";
import { readGfsInvoice } from "../src/lib/btb-gfs-reader";
import { normalizeDraft, purchaseLineDraft } from "../src/lib/btb-platform-inventory";

const source = (row = "1059292 COD FLT 4Z BLUE IQF 3 2 62.49 124.98 CS", header = "") => `Invoice #1234567890 Total Amount: $124.98 Total Items: 1 ${header} Item Code Item Description Quantity Ordered Quantity Confirmed Unit Price Item Total Sales Unit ${row} Generated by Gordon Now Application`;

test("supported Gordon Now invoices copy confirmed quantities and explicit sales units without assuming tax or dates", () => {
  const draft = readGfsInvoice(source()); assert.ok(draft);
  assert.equal(draft.vendor, "Gordon Now"); assert.equal(draft.reference, "1234567890"); assert.equal(draft.total, 124.98);
  assert.equal(draft.date, null); assert.equal(draft.gst, null); assert.equal(draft.subtotal, null);
  assert.deepEqual(draft.lines[0], { item_code: "1059292", description: "COD FLT 4Z BLUE IQF", cases: 2, packets: 0, unit_price: 62.49, line_total: 124.98, price_basis: "case" });
  assert.equal(readGfsInvoice(source("1059292 COD 3 2 62.49 124.98 EA"))!.lines[0].packets, 2);
  assert.equal(readGfsInvoice(source("1059292 COD 3 2 62.49 124.98 PK"))!.lines[0].price_basis, "packet");
  const withTax = readGfsInvoice(source(undefined, "Invoice Date: 2026-11-03 Subtotal: $119.03 GST: $5.95 Other Tax: $0 Charges: $0"))!;
  assert.equal(withTax.date, "2026-11-03"); assert.equal(withTax.gst, 5.95); assert.equal(withTax.other_tax, 0);
});

test("unsupported, partial and malformed layouts fall back instead of accepting a partial invoice", () => {
  for (const text of ["", "Other supplier Invoice #123", source().replace("Total Items: 1", "Total Items: 2"), source().replace("Sales Unit", "Unknown Unit"), source("1059292 COD 3 2 62.49 124.98 LB"), source("1059292 COD 3 -2 62.49 124.98 CS"), source("1059292 COD 3 2 62.49 124.98 CS unread footer"), source().replace("Gordon Now", "Other Application")]) assert.equal(readGfsInvoice(text), null, text);
});

test("normalization keeps absent price units and numeric invoice totals missing or explicit, never defaulting to case", () => {
  const draft = normalizeDraft("gfs", { vendor: "GFS", total: "$1,234.50", lines: [{ description: "Oil", cases: 1, packets: 0, unit_price: 40, line_total: 40 }] });
  assert.ok(draft); assert.equal(draft.total, 1234.5); assert.equal(draft.date, null); assert.equal(draft.gst, null);
  const line = (draft.lines as Record<string, unknown>[])[0]; assert.equal(line.price_basis, null); assert.equal(purchaseLineDraft(line).price_basis, "");
  assert.equal(normalizeDraft("gfs", { vendor: "GFS", total: "" })!.total, null);
});
