test("inventory review → duplicate protection → complete close → carry-forward and audited correction",async(t)=>{
  const db=await createPlatformDatabase();t.after(()=>db.close());await seedPlatform(db);
  const run=(action,data,month="2026-11")=>call(db,"btb_platform_inventory",{...manager,p_month:month,p_action:action,p_data:data});
  await run("items",{review_confirmed:true,items:[{name:"Fixture ingredient",item_number:"TEST-1",source:"gfs",pack_size:10,case_price:100,packet_price:10,unit_size:"10 × 1 kg",category:"Food"}]});
  const item=(await read(db,manager,"inventory")).items[0];
  await assert.rejects(run("finalize",{version:0}),/Opening inventory missing/);
  assert.equal((await read(db,manager,"inventory")).summary,null,"failed close rolls back summary insertion");
  const invoice=await platformImport(db,"gfs");
  const purchase={import_id:invoice.id,vendor:"Fixture supplier",date:"2026-11-03",reference:"TEST-INVOICE-1",currency:"CAD",total:800,review_confirmed:true,lines:[{item_id:item.id,description:item.name,cases:8,packets:0,line_total:800}]};
  await run("confirm_purchase",purchase);
  await assert.rejects(run("confirm_purchase",purchase),/already confirmed/);
  const duplicate=await platformImport(db,"gfs");
  await assert.rejects(run("confirm_purchase",{...purchase,import_id:duplicate.id}),/duplicate key/);
  assert.equal((await read(db,manager,"inventory")).purchases.length,1);
  await run("reject_import",{import_id:duplicate.id,reason:"Duplicate source"});
  await run("counts",{version:0,counts:[{item_id:item.id,cases:2,packets:5}]});
  await run("inputs",{version:1,opening:1000,opening_reason:"Verified opening source",purchases_confirmed:true});
  const sales=await platformImport(db,"sales");
  await run("confirm_sales",{version:2,import_id:sales.id,month:"2026-11",review_confirmed:true,basis:"Net sales",figures:[{label:"Net sales",value:5000},{label:"Gross sales",value:5500}]});
  let data=await read(db,manager,"inventory");
  assert.equal(data.summary.sales,5000);assert.equal(data.counts[0].line_value,250);
  const unknown=await platformImport(db,"local");
  await assert.rejects(run("finalize",{version:3}),/Unreviewed documents/);
  await run("reject_import",{import_id:unknown.id,reason:"Not a purchase"});
  const snapshot=await run("finalize",{version:3});
  assert.equal(snapshot.cogs,1550);assert.equal(snapshot.food_cost_pct,31);assert.equal(snapshot.item_snapshot.length,1);
  await assert.rejects(run("counts",{version:4,counts:[]}),/finalized/);
  await assert.rejects(platformImport(db,"local"),/finalized/);
  await assert.rejects(call(db,"btb_platform_inventory",{...corporate,p_month:"2026-11",p_action:"reopen",p_data:{reason:"No permission"}}),/Role not permitted/);
  await run("counts",{version:0,counts:[{item_id:item.id,cases:1,packets:0}]},"2026-12");
  await run("inputs",{version:1,purchases_confirmed:true},"2026-12");
  const nextSales=await platformImport(db,"sales","2026-12");
  await run("confirm_sales",{version:2,import_id:nextSales.id,month:"2026-12",review_confirmed:true,basis:"Net",figures:[{label:"Net",value:1000}]},"2026-12");
  const next=await run("finalize",{version:3},"2026-12");
  assert.equal(next.opening_value,250);assert.equal(next.cogs,150);
  await assert.rejects(run("reopen",{reason:"Correction"}),/downstream/);
  await run("reopen",{reason:"Unwind carry-forward"},"2026-12");
  await run("reopen",{reason:"Correct closing count"});
  await run("counts",{version:4,counts:[{item_id:item.id,cases:3,packets:0}]});
  const revised=await run("finalize",{version:5});
  assert.equal(revised.version,2);assert.equal(revised.closing_value,300);
  data=await read(db,manager,"inventory");assert.equal(data.audit.length,3);
  await assert.rejects(read(db,{...manager,p_location:IDS.b},"inventory"),/Location not permitted/);
});

test("workflow A: request approval, assignment, immutable artwork, feedback and calendar approval",async(t)=>{
  const db=await createPlatformDatabase();t.after(()=>db.close());await seedPlatform(db);
  const run=(context,action,data)=>call(db,"btb_platform_marketing",{...context,p_profile:IDS.uploader,p_action:action,p_data:data});
  let p=await run(manager,"create",{id:randomUUID(),title:"Fixture promotion",purpose:"Fixture acceptance",dimensions:{width:8,height:11,unit:"in"},required_file_type:"pdf",promotion_start:"2026-11-10",promotion_end:"2026-11-20",delivery_date:"2026-11-09"});
  p=await run(manager,"submit",{id:p.id,version:p.version});
  assert.equal(p.workflow_status,"pending_approval");
  assert.equal((await read(db,designer,"marketing")).promotions.length,0);
  await assert.rejects(run(designer,"start",{id:p.id,version:p.version}),/Corporate approval/);
  await assert.rejects(run(manager,"approve",{id:p.id,version:p.version}),/Role not permitted/);
  p=await run(corporate,"approve",{id:p.id,version:p.version});
  await assert.rejects(run(designer,"approve",{id:p.id,version:p.version}),/transition/);
  p=await run(corporate,"assign",{id:p.id,version:p.version,designer_id:IDS.designer});
  p=await run(designer,"start",{id:p.id,version:p.version});
  const file=await platformFile(db,"artwork",IDS.designer);
  p=await run(designer,"upload",{id:p.id,version:p.version,file_id:file.id,notes:"Version one"});
  p=await run(manager,"revision",{id:p.id,version:p.version,reason:"Change date emphasis"});
  const file2=await platformFile(db,"artwork",IDS.designer);
  p=await run(designer,"upload",{id:p.id,version:p.version,file_id:file2.id});
  p=await run(designer,"complete",{id:p.id,version:p.version});assert.equal(p.workflow_status,"completed");
  let data=await read(db,manager,"marketing");assert.equal(data.assets.length,2);assert.equal(data.history.filter(e=>e.action==="submitted").length,1);
  const postInput={promotion_id:p.id,version:0,status:"awaiting_approval",platform:"Instagram",title:"Post",campaign_name:p.title,description:"Fixture copy",scheduled_at:"2026-11-11T18:00:00Z",design_version_id:data.assets[0].id};
  let post=await run(designer,"calendar",postInput);
  await assert.rejects(run(designer,"calendar",{...postInput,id:post.id,version:post.version,status:"approved"}),/Corporate calendar approval/);
  post=await run(corporate,"calendar",{...postInput,id:post.id,version:post.version,status:"approved"});
  post=await run(designer,"calendar",{...postInput,id:post.id,version:post.version,status:"scheduled"});assert.equal(post.workflow_status,"scheduled");
  post=await run(designer,"calendar",{...postInput,id:post.id,version:post.version,status:"scheduled",description:"New copy"});assert.equal(post.workflow_status,"awaiting_approval");
  assert.equal((await call(db,"btb_platform_file_get",{p_actor:IDS.manager,p_session:1,p_file:file.id})).sha256,file.sha256);
  await db.exec("SET ROLE service_role");
  await assert.rejects(db.query("UPDATE btb_design_versions SET notes='overwrite'"),/permission denied/);
  await db.exec("RESET ROLE");
});

test("workflows B/C: timezone schedules, frozen retries, private compliance and confirmed renewal",async(t)=>{
  const db=await createPlatformDatabase();t.after(()=>db.close());await seedPlatform(db);
  const settings=await call(db,"btb_platform_settings",{...corporate,p_version:1,p_data:{name:"Location A",timezone:"America/Edmonton",business_day_start:"04:00",report_time:"01:00",reports_enabled:true,reminders_enabled:true,settings_confirmed:true,manager_emails:["manager@test.invalid"],owner_emails:["manager@test.invalid","owner@test.invalid"],members:[IDS.staff,IDS.manager]}});
  assert.equal(settings.reminders_enabled,true);
  const file=await platformFile(db,"compliance",IDS.staff);
  const certificate={version:0,employee_id:IDS.staff,file_id:file.id,doc_type:"Food handling",name:"Fixture certificate",expiry_date:"2027-01-05",issue_date:"2026-01-05",licence_number:"TEST-ONLY"};
  await assert.rejects(call(db,"btb_platform_compliance",{...manager,p_actor:IDS.staff,p_data:certificate}),/Confirm the new expiry/);
  let doc=await call(db,"btb_platform_compliance",{...manager,p_actor:IDS.staff,p_data:{...certificate,expiry_confirmed:true}});
  await assert.rejects(call(db,"btb_platform_compliance",{...manager,p_location:IDS.b,p_data:{...certificate,id:doc.id,version:1,reason:"Bad scope",expiry_confirmed:true}}),/Location not permitted/);
  await assert.rejects(call(db,"btb_platform_file_get",{p_actor:IDS.designer,p_session:1,p_file:file.id}),/Role not permitted/);
  const now="2026-11-06T09:00:00Z";
  await call(db,"btb_schedule_automation",{p_now:now});await call(db,"btb_schedule_automation",{p_now:now});
  let jobs=(await db.query("SELECT * FROM btb_email_jobs ORDER BY dedupe_key")).rows;
  assert.equal(jobs.filter(j=>j.kind==="daily").length,2);assert.equal(jobs.filter(j=>j.kind==="expiry").length,3);
  assert.equal(jobs.find(j=>j.kind==="daily").business_date.toISOString().slice(0,10),"2026-11-05");
  const original=jobs.find(j=>j.kind==="daily").payload;
  assert.equal(original.checklists.length,0);
  const claims=(await db.query("SELECT * FROM btb_claim_email_jobs(20)")).rows;
  const daily=claims.find(j=>j.kind==="daily");
  const prepared=await call(db,"btb_prepare_email_job",{p_id:daily.id,p_lease:daily.lease_token,p_from:"sender@test.invalid",p_attachment:"Zml4dHVyZQ=="});
  const retry=await call(db,"btb_prepare_email_job",{p_id:daily.id,p_lease:daily.lease_token,p_from:"different@test.invalid",p_attachment:"changed"});
  assert.equal(retry.frozen_from,prepared.frozen_from);assert.equal(retry.attachment_base64,prepared.attachment_base64);
  const renewal=await platformFile(db,"compliance",IDS.staff);
  doc=await call(db,"btb_platform_compliance",{...manager,p_actor:IDS.staff,p_data:{...certificate,id:doc.id,version:doc.version,file_id:renewal.id,expiry_date:"2028-01-05",expiry_confirmed:true,reason:"Renewed certificate verified"}});
  const expiredClaim=claims.find(j=>j.kind==="expiry");
  assert.equal(await call(db,"btb_prepare_email_job",{p_id:expiredClaim.id,p_lease:expiredClaim.lease_token,p_from:"sender@test.invalid",p_attachment:null}),null);
  const data=await read(db,manager,"compliance");assert.equal(data.history.length,2);assert.equal(data.documents[0].expiry_date,"2028-01-05");
  assert.equal((await read(db,{...manager,p_actor:IDS.staff},"compliance")).documents.length,1);
});
